const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
    ping: () => ipcRenderer.send('ping'),
    // Window controls
    windowMinimize: () => ipcRenderer.send('window-minimize'),
    windowMaximize: () => ipcRenderer.send('window-maximize'),
    windowClose: () => ipcRenderer.send('window-close'),
    dbStatus: () => ipcRenderer.invoke('db-status'),
    login: (credentials) => ipcRenderer.invoke('login', credentials),
    signup: (credentials) => ipcRenderer.invoke('signup', credentials),
    getModules: () => ipcRenderer.invoke('get-modules'),
    getPermissions: (role) => ipcRenderer.invoke('get-permissions', role),
    updatePermissions: (permissions) => ipcRenderer.invoke('update-permissions', permissions),
    // User Management
    getUsers: () => ipcRenderer.invoke('get-users'),
    getUser: (userId) => ipcRenderer.invoke('get-user', userId),
    createUser: (data) => ipcRenderer.invoke('create-user', data),
    updateUser: (data) => ipcRenderer.invoke('update-user', data),
    deleteUser: (data) => ipcRenderer.invoke('delete-user', data),
    // Roles
    'get-roles': () => ipcRenderer.invoke('get-roles'),
    'create-role': (data) => ipcRenderer.invoke('create-role', data),
    'update-role': (data) => ipcRenderer.invoke('update-role', data),
    'delete-role': (data) => ipcRenderer.invoke('delete-role', data),
    // Profile & Auth
    getMe: (data) => ipcRenderer.invoke('get-me', data),
    updateProfile: (data) => ipcRenderer.invoke('update-profile', data),
    resetPassword: (data) => ipcRenderer.invoke('reset-password', data),
    // SKU & Categories
    getRackMonitoring: () => ipcRenderer.invoke('get-rack-monitoring'),
    getCategories: () => ipcRenderer.invoke('get-categories'),
    createCategory: (data) => ipcRenderer.invoke('create-category', data),
    getSubCategories: (categoryId) => ipcRenderer.invoke('get-subcategories', categoryId),
    createSubCategory: (data) => ipcRenderer.invoke('create-subcategory', data),
    updateCategory: (data) => ipcRenderer.invoke('update-category', data),
    updateSubCategory: (data) => ipcRenderer.invoke('update-subcategory', data),
    getSkus: () => ipcRenderer.invoke('get-skus'),
    createSku: (data) => ipcRenderer.invoke('create-sku', data),
    updateSku: (data) => ipcRenderer.invoke('update-sku', data),
    deleteSku: (data) => ipcRenderer.invoke('delete-sku', data),
    createBilling: (data) => ipcRenderer.invoke('create-billing', data),
    getInvoices: () => ipcRenderer.invoke('get-invoices'),
    getInvoicesSummary: () => ipcRenderer.invoke('get-invoices-summary'),
    getInvoicesMonthlyRevenue: () => ipcRenderer.invoke('get-invoices-monthly-revenue'),
    getInvoicesMonthlyVolume: () => ipcRenderer.invoke('get-invoices-monthly-volume'),
    updateInvoiceStatus: (data) => ipcRenderer.invoke('update-invoice-status', data),
    getCompanySettings: () => ipcRenderer.invoke('get-company-settings'),
    saveCompanySettings: (data) => ipcRenderer.invoke('save-company-settings', data),
    getCustomers: () => ipcRenderer.invoke('get-customers'),
    createCustomer: (data) => ipcRenderer.invoke('create-customer', data),
    getDashboardMetrics: () => ipcRenderer.invoke('get-dashboard-metrics'),

    // ── PLC Control ──────────────────────────────────────────────────────────
    plc: {
        getStatus:       ()       => ipcRenderer.invoke('plc-status'),
        connect:         (cfg)    => ipcRenderer.invoke('plc-connect', cfg),
        disconnect:      ()       => ipcRenderer.invoke('plc-disconnect'),
        writeTag:        (name, v)=> ipcRenderer.invoke('plc-write-tag', { tagName: name, value: v }),
        readTag:         (name)   => ipcRenderer.invoke('plc-read-tag', { tagName: name }),
        writeCoil:       (t,a,v)  => ipcRenderer.invoke('plc-write-coil', { type: t, address: a, value: v }),
        readCoil:        (t,a,c)  => ipcRenderer.invoke('plc-read-coil',  { type: t, address: a, count: c }),
        writeRegister:   (t,a,v)  => ipcRenderer.invoke('plc-write-register', { type: t, address: a, value: v }),
        readRegister:    (t,a,c)  => ipcRenderer.invoke('plc-read-register',  { type: t, address: a, count: c }),
        getSettings:     ()       => ipcRenderer.invoke('plc-get-settings'),
        saveSettings:    (cfg)    => ipcRenderer.invoke('plc-save-settings', cfg),
        getTags:         ()       => ipcRenderer.invoke('plc-get-tags'),
        saveTags:        (tags)   => ipcRenderer.invoke('plc-save-tags', tags),
        getLogs:         (opts)   => ipcRenderer.invoke('plc-get-logs', opts),
        clearLogs:       ()       => ipcRenderer.invoke('plc-clear-logs'),
    },
});
